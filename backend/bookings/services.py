"""
Booking service layer.   Owner: Amina A. (transactions/locking) + Aitore (rejected-booking handling)

create_booking is ONE transaction (Task 9 transaction, rule 10):
   lock departure row -> checks -> seats - n -> insert Pending (total_cost frozen) -> audit row.
If any step raises, everything is rolled back, so no half-finished booking survives.
The payment step joins the same transaction in bookings.payments.book_and_pay (checkout), where a failed payment
rolls the whole booking back. "Needs review" handling comes in Phase 3.
"""
from datetime import timedelta
from decimal import Decimal
import uuid

from django.conf import settings
from django.db import IntegrityError, transaction
from django.utils import timezone

from catalog.models import Departure
from catalog.services import next_available_departure
from core.exceptions import ApiError

from .models import AuditLog, Booking


def _rejected(code, key, message, status_code, departure, min_seats=1):
    """Lab 4 acceptance criterion: every rejection carries the guide's NEXT available departure."""
    return ApiError(code, key, message, status_code, extra={
        "next_available_departure": next_available_departure(departure.guide_id, min_seats, exclude_departure_id=departure.pk)})


def create_booking(user, departure_id, travelers_count, special_request=""):
    try:
        with transaction.atomic():
            # select_for_update(of=("self",)) = row lock on the departure only (ignored by SQLite).
            # A second tourist booking the last seat waits here until we commit, then sees 0 seats.
            try:
                dep = (Departure.objects.select_for_update(of=("self",))
                       .select_related("package", "guide")
                       .get(pk=departure_id, is_active=True, package__is_active=True, guide__is_active=True))
            except Departure.DoesNotExist:
                raise ApiError("departure_not_found", "errors.booking.departure_not_found",
                               "This departure does not exist.", 404)

            now = timezone.now()
            if dep.start_at <= now:
                raise _rejected("departure_in_past", "errors.booking.departure_in_past",
                                "This departure has already started.", 422, dep, travelers_count)

            if Booking.objects.filter(user=user, departure=dep, status__in=Booking.ACTIVE).exists():
                raise ApiError("duplicate_booking", "errors.booking.duplicate",
                               "You already booked this departure.", 409)

            if dep.seats_available < travelers_count:
                raise _rejected("departure_full", "errors.booking.departure_full",
                                "Not enough free seats on this departure.", 409, dep, travelers_count)

            dep.seats_available -= travelers_count
            dep.save(update_fields=["seats_available"])      # CHECK 0 <= seats <= total is the safety net

            booking = Booking.objects.create(
                booking_ref=f"TMP-{uuid.uuid4().hex[:8]}",   # replaced below; unique placeholder
                user=user, departure=dep,
                booking_date=timezone.localdate(),
                travel_date=timezone.localtime(dep.start_at).date(),
                travelers_count=travelers_count,
                total_cost=(dep.package.base_price * Decimal(travelers_count)).quantize(Decimal("0.01")),
                status=Booking.PENDING,
                special_request=special_request,
                expires_at=now + timedelta(hours=settings.PENDING_BOOKING_HOURS),
            )
            booking.booking_ref = f"BK-{booking.pk:04d}"       # generated by the system only
            booking.save(update_fields=["booking_ref"])

            AuditLog.objects.create(user=user, action="create", table_name="bookings", record_id=booking.pk,
                                    new_value={"ref": booking.booking_ref, "status": booking.status,
                                               "departure": dep.pk, "travelers": travelers_count,
                                               "total_cost": str(booking.total_cost)})
            return booking
    except IntegrityError:
        # A DB rule caught something the checks above missed (e.g. a race on the partial unique index).
        raise ApiError("duplicate_booking", "errors.booking.duplicate", "You already booked this departure.", 409)
