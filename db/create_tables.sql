CREATE EXTENSION IF NOT EXISTS btree_gist;   -- lets "guide_id WITH =" live in a GiST index

-- ---------- roles & users -------------------------------------------
CREATE TABLE roles (
    role_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(20) NOT NULL UNIQUE,
    CONSTRAINT ck_roles_name CHECK (name IN ('tourist','guide','manager','analyst','admin'))
);

-- Tourists are users with role = 'tourist' (ER slide label: "CUSTOMERS / users")
CREATE TABLE users (
    user_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(254) NOT NULL UNIQUE,
    password_hash      VARCHAR(128) NOT NULL,                  -- never plain text
    full_name          VARCHAR(150) NOT NULL,
    phone              VARCHAR(30)  NOT NULL DEFAULT '',
    role_id            INTEGER NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
    preferred_language VARCHAR(2)   NOT NULL DEFAULT 'en',
    mfa_enabled        BOOLEAN      NOT NULL DEFAULT FALSE,
    mfa_secret         VARCHAR(64)  NOT NULL DEFAULT '',       -- TOTP secret (Phase 2)
    failed_login_count SMALLINT     NOT NULL DEFAULT 0,
    locked_until       TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_users_language CHECK (preferred_language IN ('en','ru','kk')),
    CONSTRAINT ck_users_email_format CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_users_failed_login CHECK (failed_login_count >= 0)
);

CREATE TABLE guides (
    guide_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INTEGER NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE RESTRICT,
    bio              TEXT NOT NULL DEFAULT '',
    languages_spoken VARCHAR(40) NOT NULL DEFAULT 'en',        -- comma list: en,ru,kk
    is_active        BOOLEAN NOT NULL DEFAULT TRUE             -- deactivate, never delete
);

-- ---------- catalogue -----------------------------------------------
CREATE TABLE destinations (
    destination_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120) NOT NULL,
    country        VARCHAR(80)  NOT NULL,
    CONSTRAINT uq_destinations_name_country UNIQUE (name, country)
);

CREATE TABLE tour_packages (
    package_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id          INTEGER NOT NULL REFERENCES destinations(destination_id) ON DELETE RESTRICT,
    base_price              NUMERIC(10,2) NOT NULL,
    duration_days           INTEGER NOT NULL,
    accommodation_included  BOOLEAN NOT NULL DEFAULT FALSE,    -- flag only, no hotel tables
    transport_included      BOOLEAN NOT NULL DEFAULT FALSE,    -- flag only, no transport tables
    is_active               BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_packages_price    CHECK (base_price >= 0),
    CONSTRAINT ck_packages_duration CHECK (duration_days > 0)
);

CREATE TABLE package_translations (
    translation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id     INTEGER NOT NULL REFERENCES tour_packages(package_id) ON DELETE RESTRICT,
    language_code  VARCHAR(2) NOT NULL,
    title          VARCHAR(200) NOT NULL,
    description    TEXT NOT NULL DEFAULT '',
    CONSTRAINT uq_translation_package_lang UNIQUE (package_id, language_code),
    CONSTRAINT ck_translation_lang CHECK (language_code IN ('en','ru','kk'))
);

-- A departure = one package + one guide at a fixed time (seats_total = 1 => private tour)
CREATE TABLE departures (
    departure_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id      INTEGER NOT NULL REFERENCES tour_packages(package_id) ON DELETE RESTRICT,
    guide_id        INTEGER NOT NULL REFERENCES guides(guide_id) ON DELETE RESTRICT,
    start_at        TIMESTAMPTZ NOT NULL,
    end_at          TIMESTAMPTZ NOT NULL,
    seats_total     INTEGER NOT NULL,
    seats_available INTEGER NOT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,             -- deactivate, never delete; inactive slots free the guide's time
    CONSTRAINT ck_departures_time  CHECK (end_at > start_at),
    CONSTRAINT ck_departures_total CHECK (seats_total > 0),
    CONSTRAINT ck_departures_seats CHECK (seats_available >= 0 AND seats_available <= seats_total),
    -- BR-01 / FR-01: the same guide can never have two overlapping ACTIVE slots ('[)' ranges: back-to-back is fine)
    CONSTRAINT ex_departures_guide_no_overlap
        EXCLUDE USING gist (guide_id WITH =, tstzrange(start_at, end_at) WITH &&) WHERE (is_active)
);

-- ---------- bookings, payments --------------------------------------
CREATE TABLE bookings (
    booking_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_ref     VARCHAR(12) NOT NULL UNIQUE,              -- "BK-0001", system-generated only
    user_id         INTEGER NOT NULL REFERENCES users(user_id)           ON DELETE RESTRICT,
    departure_id    INTEGER NOT NULL REFERENCES departures(departure_id) ON DELETE RESTRICT,
    booking_date    DATE NOT NULL,
    travel_date     DATE NOT NULL,
    travelers_count INTEGER NOT NULL,
    total_cost      NUMERIC(10,2) NOT NULL,                   -- base_price x travelers, frozen at booking time
    status          VARCHAR(20) NOT NULL DEFAULT 'Pending',
    special_request TEXT NOT NULL DEFAULT '',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ,                              -- Pending: created_at + 48 h
    CONSTRAINT ck_bookings_dates     CHECK (travel_date >= booking_date),
    CONSTRAINT ck_bookings_travelers CHECK (travelers_count > 0),
    CONSTRAINT ck_bookings_cost      CHECK (total_cost >= 0),
    CONSTRAINT ck_bookings_status    CHECK (status IN ('Pending','Confirmed','Cancelled','Completed','Needs review'))
);
-- Rule 4: one ACTIVE booking per tourist per departure (fixes the "P4 duplicate" record)
CREATE UNIQUE INDEX uq_bookings_active_user_departure
    ON bookings (user_id, departure_id) WHERE status IN ('Pending','Confirmed');

CREATE TABLE payments (
    payment_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    amount          NUMERIC(10,2) NOT NULL,
    status          VARCHAR(10) NOT NULL,
    transaction_ref VARCHAR(40) NOT NULL UNIQUE,
    paid_at         TIMESTAMPTZ,
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_status CHECK (status IN ('Success','Failed'))
);

-- ---------- reviews, notifications, audit ---------------------------
CREATE TABLE reviews (
    review_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    package_id  INTEGER NOT NULL REFERENCES tour_packages(package_id) ON DELETE RESTRICT,
    rating      SMALLINT NOT NULL,
    comment     TEXT NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT uq_reviews_user_package UNIQUE (user_id, package_id)
);

CREATE TABLE notifications (
    notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    booking_id      INTEGER REFERENCES bookings(booking_id) ON DELETE RESTRICT,   -- nullable
    type            VARCHAR(30) NOT NULL,        -- created / confirmed / cancelled / expired
    message_key     VARCHAR(100) NOT NULL,       -- translated by the frontend
    params          JSONB NOT NULL DEFAULT '{}',
    is_read         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_log (
    audit_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER REFERENCES users(user_id) ON DELETE RESTRICT,  -- NULL = done by the system
    action      VARCHAR(30) NOT NULL,
    table_name  VARCHAR(60) NOT NULL,
    record_id   INTEGER,
    old_value   JSONB,
    new_value   JSONB,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- indexes (rule 11) ---------------------------------------
CREATE INDEX ix_departures_start_at    ON departures (start_at);
CREATE INDEX ix_departures_guide       ON departures (guide_id);
CREATE INDEX ix_bookings_user          ON bookings (user_id);
CREATE INDEX ix_bookings_departure     ON bookings (departure_id);
CREATE INDEX ix_packages_destination   ON tour_packages (destination_id);
CREATE INDEX ix_notifications_user_read ON notifications (user_id, is_read);
CREATE INDEX ix_audit_table_record     ON audit_log (table_name, record_id);
CREATE INDEX ix_package_translations_fts
    ON package_translations USING gin (to_tsvector('simple', title || ' ' || description));

-- ---------- rule 12: analyst sees aggregates only -------------------
-- No email, no phone, no names. Packages with zero bookings still show 0 (LEFT JOIN).
-- active = Pending + Confirmed (Task 9 definition); revenue = successful payments only.
CREATE VIEW analyst_booking_view AS
SELECT p.package_id,
       COALESCE(t.title, '(no English title)')                                          AS package_title,
       COUNT(b.booking_id) FILTER (WHERE b.status IN ('Pending', 'Confirmed'))          AS active_bookings,
       COUNT(b.booking_id) FILTER (WHERE b.status = 'Completed')                        AS completed_bookings,
       COUNT(b.booking_id) FILTER (WHERE b.status = 'Cancelled')                        AS cancelled_bookings,
       COALESCE(SUM(pay.paid), 0)::numeric(12, 2)                                       AS revenue
FROM tour_packages p
LEFT JOIN package_translations t ON t.package_id = p.package_id AND t.language_code = 'en'
LEFT JOIN departures d           ON d.package_id = p.package_id
LEFT JOIN bookings b             ON b.departure_id = d.departure_id
LEFT JOIN (SELECT booking_id, SUM(amount) AS paid FROM payments WHERE status = 'Success' GROUP BY booking_id) pay
                                 ON pay.booking_id = b.booking_id
GROUP BY p.package_id, t.title;
